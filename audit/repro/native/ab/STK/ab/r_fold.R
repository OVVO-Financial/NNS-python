suppressPackageStartupMessages(library(NNS))
X <- read.csv("dump/f1_x.csv", header=FALSE); names(X) <- c("Xstar","Xstar2"); y <- scan("dump/f1_y.csv", quiet=TRUE)
Xt <- read.csv("dump/f1_xt.csv", header=FALSE); names(Xt) <- names(X)
s <- NNS:::.nns_mreg_prepare_model(X, y, order=NULL, noise.reduction="off", is.class=FALSE)
rpm <- s$RPM; prx <- as.matrix(read.csv("dump/f1_rpmx.csv", header=FALSE)); pry <- scan("dump/f1_rpmy.csv", quiet=TRUE)
cat("RPM rows R", nrow(rpm), " py", nrow(prx), "\n")
if (nrow(rpm)==nrow(prx)) cat("rpm diff", max(abs(as.matrix(rpm[,1:2])-prx)), max(abs(rpm$y.hat-pry)), "\n")
kmax <- min(floor(sqrt(nrow(X)+ 0)), nrow(rpm))
path <- NNS:::NNS_mreg_predict_path_v2_cpp(as.matrix(rpm[,1:2]), rpm$y.hat, as.matrix(Xt), as.integer(ncol(as.matrix(read.csv("dump/f1_path.csv",header=FALSE)))), 0L, sapply(X,min), sapply(X,max), FALSE, 1L)
pp <- as.matrix(read.csv("dump/f1_path.csv", header=FALSE))
cat("path diff per k:", round(apply(abs(path-pp),2,max),5), "\n")
path2 <- NNS:::NNS_mreg_predict_path_v2_cpp(prx, pry, as.matrix(Xt), ncol(pp), 0L, sapply(X,min), sapply(X,max), FALSE, 1L)
cat("path(py rpm) diff per k:", round(apply(abs(path2-pp),2,max),5), "\n")
