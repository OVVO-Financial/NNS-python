import numpy as np, pandas as pd, nns, inspect, traceback
rng=np.random.default_rng(0); x=rng.normal(size=100); y=x+rng.normal(size=100)
def t(label, f):
    try: print(label, "->", f())
    except Exception as e: print(label, "-> ERR", type(e).__name__, e)
for fn in [nns.nns_dep, nns.nns_cor, nns.nns_copula, nns.nns_causation, nns.causal_matrix, nns.nns_part]:
    print(fn.__name__, inspect.signature(fn))
M=np.column_stack([x,y,rng.normal(size=100)])
t("dep matrix x only", lambda: nns.nns_dep(M))
t("dep matrix y None", lambda: nns.nns_dep(M, None))
t("dep DataFrame", lambda: nns.nns_dep(pd.DataFrame(M)))
t("dep pandas series", lambda: nns.nns_dep(pd.Series(x), pd.Series(y)))
t("dep int dtype", lambda: nns.nns_dep(np.arange(20), np.arange(20)[::-1]**2))
t("dep list", lambda: nns.nns_dep([1,2,3,4,5],[2,1,4,3,5]))
t("dep nan", lambda: nns.nns_dep(np.r_[x[:-1],np.nan], y))
t("dep len1", lambda: nns.nns_dep([1.],[2.]))
t("dep len2", lambda: nns.nns_dep([1.,2],[2.,1]))
t("dep empty", lambda: nns.nns_dep([],[]))
t("dep column vec (n,1)", lambda: nns.nns_dep(x.reshape(-1,1), y.reshape(-1,1)))
t("dep p_value kw", lambda: nns.nns_dep(x,y,p_value=True))
t("copula nan", lambda: nns.nns_copula(np.r_[x[:-1],np.nan], y))
t("copula inf", lambda: nns.nns_copula(np.r_[x[:-1],np.inf], y))
# copula empty segfaults: see segv_copula.py
t("copula len1", lambda: nns.nns_copula([1.],[2.]))
t("copula matrix 3", lambda: nns.nns_copula(M))
t("copula DataFrame", lambda: nns.nns_copula(pd.DataFrame(M)))
t("copula target", lambda: nns.nns_copula(M, target=[0,0,0]))
t("copula 1 col", lambda: nns.nns_copula(M[:,:1]))
t("caus nan", lambda: nns.nns_causation(np.r_[x[:-1],np.nan], y))
t("caus tau cs", lambda: nns.nns_causation(x,y,tau="cs"))
t("caus tau 'ts'", lambda: nns.nns_causation(x,y,tau="ts"))
t("caus tau float 1.5", lambda: nns.nns_causation(x,y,tau=1.5))
t("caus tau neg", lambda: nns.nns_causation(x,y,tau=-1))
t("caus tau huge", lambda: nns.nns_causation(x,y,tau=200))
t("caus tau 'foo'", lambda: nns.nns_causation(x,y,tau="foo"))
t("caus tau np.int64", lambda: nns.nns_causation(x,y,tau=np.int64(2)))
t("caus len3", lambda: nns.nns_causation([1.,2,3],[3.,1,2]))
t("causal_matrix DataFrame", lambda: nns.causal_matrix(pd.DataFrame(M, columns=list("abc"))))
t("causal_matrix 1col", lambda: nns.causal_matrix(M[:,:1]))
t("part order np.int64", lambda: nns.nns_part(x,y,order=np.int64(3))["order"])
t("part order 3.0", lambda: nns.nns_part(x,y,order=3.0)["order"])
t("part order 0", lambda: nns.nns_part(x,y,order=0)["order"])
t("part obs_req 2.5", lambda: nns.nns_part(x,y,obs_req=2.5)["order"])
t("part type 'X'", lambda: nns.nns_part(x,y,type="X")["order"])
t("part pandas", lambda: nns.nns_part(pd.Series(x),pd.Series(y))["order"])
t("part nan", lambda: len(nns.nns_part(np.r_[x[:-1],np.nan],y)["dt"]["x"]))
t("part min_obs_stop np.bool_", lambda: nns.nns_part(x,y,min_obs_stop=np.bool_(False))["order"])
t("part noise 'MEAN'", lambda: nns.nns_part(x,y,noise_reduction="MEAN")["order"])
t("part noise 'bad'", lambda: nns.nns_part(x,y,noise_reduction="bad"))
t("part order neg", lambda: nns.nns_part(x,y,order=-2))
t("part obs_req neg", lambda: nns.nns_part(x,y,obs_req=-1))
