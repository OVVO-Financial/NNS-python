import numpy as np, pandas as pd, nns, traceback
R=pd.read_csv("/home/user/audit/data/returns_daily_equity_etf.csv", index_col=0)
def t(label, f):
    try: print(label, "->", f())
    except Exception as e: print(label, "-> EXC", type(e).__name__, e)
t("eff set DataFrame", lambda: nns.sd_efficient_set(R,2))
t("cluster DataFrame names", lambda: nns.nns_sd_cluster(R,degree=2)["Clusters"])
t("eff degree=1.5", lambda: nns.sd_efficient_set(R,1.5))
t("eff degree=3", lambda: nns.sd_efficient_set(R,3))
t("eff degree='2'", lambda: nns.sd_efficient_set(R,'2'))
t("fsd Series", lambda: nns.fsd(R["SPY"], R["TLT"]))
t("fsd 1-col DataFrame", lambda: nns.fsd(R[["SPY"]], R[["TLT"]]))
t("fsd 2-col DataFrame (R errors)", lambda: nns.fsd(R[["SPY","QQQ"]], R[["TLT","GLD"]]))
t("fsd with NaN", lambda: nns.fsd(np.r_[R["SPY"].values, np.nan], R["TLT"].values))
t("fsd empty", lambda: nns.fsd(np.array([]), np.array([1.0])))
t("fsd int", lambda: nns.fsd(np.array([1,2,3]), np.array([0,1,2])))
t("fsd_uni bad type", lambda: nns.fsd_uni([1,2,3],[0,1,2],type="contin"))
t("eff set bad type", lambda: nns.sd_efficient_set(R.values,1,type="contin"))
t("cluster min_cluster=0", lambda: nns.nns_sd_cluster(R.values,degree=2,min_cluster=0)["Clusters"])
t("cluster min_cluster=20", lambda: nns.nns_sd_cluster(R.values,degree=2,min_cluster=20))
t("cluster dendro 1 col", lambda: nns.nns_sd_cluster(R.values[:,:1],degree=2,dendrogram=True))
t("eff 1 col", lambda: nns.sd_efficient_set(R.values[:,:1],2))
t("eff 1 row", lambda: nns.sd_efficient_set(R.values[:1],2))
t("eff dup columns", lambda: nns.sd_efficient_set(np.c_[R.values[:,:2],R.values[:,:2]],2))
t("cluster dup columns", lambda: nns.nns_sd_cluster(np.c_[R.values[:,:2],R.values[:,:2]],degree=2)["Clusters"])
