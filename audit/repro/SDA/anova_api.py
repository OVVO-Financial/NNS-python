import numpy as np, pandas as pd, nns
F=pd.read_csv("/home/user/audit/data/returns_daily_equity_etf.csv",index_col=0)
aq=pd.read_csv("/home/user/audit/data/airquality.csv")
def t(l,f):
    try: r=f(); print(l,"->", r if not isinstance(r,np.ndarray) else (type(r).__name__, r.shape, r[:2,:2].round(4).tolist() if r.ndim==2 else r))
    except Exception as e: print(l,"-> EXC",type(e).__name__,e)
t("DataFrame multi", lambda: nns.nns_anova(F[["SPY","TLT","GLD"]]))
t("DataFrame pairwise (labels?)", lambda: type(nns.nns_anova(F[["SPY","TLT","GLD"]],pairwise=True)))
t("list of Series", lambda: nns.nns_anova([F.SPY,F.TLT]))
t("tuple of arrays", lambda: nns.nns_anova((F.SPY.values,F.TLT.values)))
t("airquality NaN cols (Ozone,Solar.R)", lambda: nns.nns_anova(aq[["Ozone","Solar.R"]].to_numpy()))
t("airquality binary w NaN", lambda: nns.nns_anova(aq.Ozone, aq["Solar.R"], confidence_interval=None)["Certainty"])
t("1-col matrix", lambda: nns.nns_anova(F[["SPY"]].to_numpy()))
t("ci=1.5", lambda: nns.nns_anova(F.SPY.values,F.TLT.values,confidence_interval=1.5))
t("tails bad", lambda: nns.nns_anova(F.SPY.values,F.TLT.values,tails="two"))
t("len1 groups", lambda: nns.nns_anova(np.array([1.0]),np.array([2.0]),confidence_interval=None))
t("len2 groups", lambda: nns.nns_anova(np.array([1.0,2]),np.array([2.0,3]),confidence_interval=None))
t("int dtype", lambda: nns.nns_anova(np.array([1,2,3,4]),np.array([2,3,4,5]),confidence_interval=None)["Certainty"])
t("robust ci=None", lambda: nns.nns_anova(F.SPY.values[:100],F.TLT.values[:100],robust=True,confidence_interval=None))
t("Inf in data", lambda: nns.nns_anova(np.r_[F.SPY.values[:100],np.inf],F.TLT.values[:100],confidence_interval=None)["Certainty"])
